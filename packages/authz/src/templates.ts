/**
 * Shipped role templates (ADM-04): built from the WESTWIND cast (docs/02), the
 * field and frontline roles (docs/03, docs/04) and the original A7 personas.
 * A county copies and edits these; it cannot grant the template-protected
 * categories (ADM-05 guardrail 7) — those come only from the template key.
 * Grants here cover layer-1 actions; each layer adds its own.
 */
import type { DataCategory, Grant } from './types.ts';

export interface RoleTemplate {
  key: string;
  name: string;
  description: string;
  source: 'cast' | 'field' | 'frontline' | 'original_a7' | 'platform';
  grants: Grant[];
  /** An assignment must end within this many days of being requested (time-limited roles). */
  maxAssignmentDays?: number;
}

/** Which templates may see each protected category (RULE-16, FL:FR-15/16/23/25). */
export const CATEGORY_TEMPLATES: Partial<Record<DataCategory, string[]>> = {
  health: ['shelter_nurse'],
  counseling: ['crisis_counselor'],
  legal: ['legal_aid_attorney'],
  access_needs: ['afn_coordinator', 'shelter_nurse', 'disability_advocate'],
};

const g = (action: string, dataCategories?: DataCategory[]): Grant =>
  dataCategories ? { action, dataCategories } : { action };

/** A frontline role in the field app: the common field grants plus its own records (layer-4 plan §8). */
function frontline(
  key: string,
  name: string,
  description: string,
  own: (string | Grant)[],
): RoleTemplate[] {
  return [
    {
      key,
      name,
      description,
      source: 'frontline',
      grants: [
        g('me.read'),
        { action: 'event.read', events: 'assigned' },
        g('team.read'),
        g('check_in.create'),
        g('check_in.end'),
        g('device.register'),
        g('position.record'),
        g('parcel.read'),
        { action: 'mission.read', events: 'assigned', records: 'own' },
        { action: 'assignment.read', records: 'own' },
        { action: 'assignment.acknowledge', records: 'own' },
        { action: 'assignment.status', records: 'own' },
        g('hazard.read'),
        g('hazard.report'),
        g('field_report.write'), // FLD-11
        g('field_message.read'),
        g('field_message.receipt'),
        g('safety_alert.raise'),
        g('service_log.write'),
        g('job_aid.read'),
        g('activity.read'),
        g('field.sync'),
        g('field.command'),
        // FL-16: anyone in the field may ask, privately, for peer support.
        g('peer_support.request'),
        g('field.photo'),
        g('field.area'),
        ...own.map((x) => (typeof x === 'string' ? g(x) : x)),
      ],
    },
  ];
}

