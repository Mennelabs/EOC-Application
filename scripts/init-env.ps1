<#
.SYNOPSIS
  Writes .env with random LOCAL-ONLY secrets. Windows counterpart of
  scripts/init-env.sh (CLAUDE.md rule 9: no secrets in code; SCL-11).
.DESCRIPTION
  Safe to re-run: keeps an existing .env unless -Force is given.
  Run from PowerShell in the repository:  .\scripts\init-env.ps1
  If scripts are blocked:  powershell -ExecutionPolicy Bypass -File scripts\init-env.ps1
#>
[CmdletBinding()]
param([switch]$Force)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'

if ((Test-Path $envFile) -and -not $Force) {
  Write-Host ".env already exists (use -Force to regenerate; this resets local data access)."
  exit 0
}

function New-Secret {
  # 32 characters from A-Za-z0-9 using the OS cryptographic generator.
  # Works on Windows PowerShell 5.1 and PowerShell 7.
  $alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  $out = New-Object System.Text.StringBuilder
  $buf = New-Object byte[] 64
  while ($out.Length -lt 32) {
    $rng.GetBytes($buf)
    foreach ($b in $buf) {
      # Reject values that would bias the modulo (248 = 4 * 62).
      if ($b -lt 248 -and $out.Length -lt 32) { [void]$out.Append($alphabet[$b % 62]) }
    }
  }
  $rng.Dispose()
  return $out.ToString()
}

$lines = @(
  '# Generated by scripts/init-env.ps1 - LOCAL DEVELOPMENT ONLY. Never commit.',
  'PRODUCT_NAME="Common Ground"',
  'COUNTY_NAME="Westwind County"',
  'HELP_PHONE="(314) 555-0142"',
  'GATEWAY_HOST=localhost',
  'COMPOSE_PROFILES=',
  '',
  "POSTGRES_PASSWORD=$(New-Secret)",
  "CG_MIGRATOR_PASSWORD=$(New-Secret)",
  "CG_APP_PASSWORD=$(New-Secret)",
  "CG_WORKER_PASSWORD=$(New-Secret)",
  "KEYCLOAK_DB_PASSWORD=$(New-Secret)",
  "KEYCLOAK_ADMIN_PASSWORD=$(New-Secret)",
  "RABBITMQ_PASSWORD=$(New-Secret)",
  "MINIO_ROOT_PASSWORD=$(New-Secret)",
  "CJIS_POSTGRES_PASSWORD=$(New-Secret)",
  "CJIS_APP_PASSWORD=$(New-Secret)",
  "RESIDENT_TOKEN_SECRET=$(New-Secret)"
# Optional real texting (docs/06); empty keeps the simulator.
TWILIO_ACCOUNT_SID=
TWILIO_AUTH_TOKEN=
WEBHOOK_PUBLIC_BASE=
)

# UTF-8 without a byte-order mark and LF endings: Docker Compose reads the
# file byte for byte, and a BOM would become part of the first variable name.
$content = ($lines -join "`n") + "`n"
[System.IO.File]::WriteAllText($envFile, $content, (New-Object System.Text.UTF8Encoding $false))
Write-Host "Wrote .env with fresh local secrets."
