#!/bin/sh
# Writes .env with random local-only secrets (CLAUDE.md rule 9: no secrets in
# code). Safe to re-run: an existing .env keeps its values and only gains the
# variables a newer checkout needs (layer 5 added the CJIS enclave's), unless
# --force regenerates everything (this resets local data access).
set -eu
cd "$(dirname "$0")/.."
rand() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32; }
umask 077

if [ -f .env ] && [ "${1:-}" != "--force" ]; then
  added=""
  for name in CJIS_MIGRATOR_PASSWORD CJIS_JOB_PASSWORD CJIS_IDP_DB_PASSWORD CJIS_KEYCLOAK_ADMIN_PASSWORD CJIS_IDP_ADMIN_CLIENT_SECRET; do
    if ! grep -q "^${name}=" .env; then
      echo "${name}=$(rand)" >> .env
      added="${added} ${name}"
    fi
  done
  if [ -n "$added" ]; then
    echo "Added to .env:${added}."
    echo "The CJIS enclave database gained roles in layer 5: if it was created before, recreate it with"
    echo "  docker compose rm -sf cjis-db && docker volume rm common-ground_cjis_db_data"
  else
    echo ".env already exists (use --force to regenerate; this resets local data access)."
  fi
  exit 0
fi
cat > .env <<ENV
# Generated by scripts/init-env.sh — LOCAL DEVELOPMENT ONLY. Never commit.
PRODUCT_NAME="Common Ground"
COUNTY_NAME="Westwind County"
HELP_PHONE="(314) 555-0142"
GATEWAY_HOST=localhost
COMPOSE_PROFILES=

POSTGRES_PASSWORD=$(rand)
CG_MIGRATOR_PASSWORD=$(rand)
CG_APP_PASSWORD=$(rand)
CG_WORKER_PASSWORD=$(rand)
KEYCLOAK_DB_PASSWORD=$(rand)
KEYCLOAK_ADMIN_PASSWORD=$(rand)
RABBITMQ_PASSWORD=$(rand)
MINIO_ROOT_PASSWORD=$(rand)
CJIS_POSTGRES_PASSWORD=$(rand)
CJIS_MIGRATOR_PASSWORD=$(rand)
CJIS_APP_PASSWORD=$(rand)
CJIS_JOB_PASSWORD=$(rand)
CJIS_IDP_DB_PASSWORD=$(rand)
CJIS_KEYCLOAK_ADMIN_PASSWORD=$(rand)
CJIS_IDP_ADMIN_CLIENT_SECRET=$(rand)
RESIDENT_TOKEN_SECRET=$(rand)
# Optional real texting (docs/06); empty keeps the simulator.
TWILIO_ACCOUNT_SID=
TWILIO_AUTH_TOKEN=
WEBHOOK_PUBLIC_BASE=
# Abuse protection per address (SEC-17); raise the deny limit only for a load generator on one host.
PUBLIC_IP_VERIFY_PER_10MIN=20
PUBLIC_IP_DENY_PER_10MIN=120
ENV
echo "Wrote .env with fresh local secrets."
