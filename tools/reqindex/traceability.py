#!/usr/bin/env python3
"""Build docs/traceability.md from requirements.json and trace-layer1.json.

Every ID in build layers covered so far (layer 1 and the cross-cutting set)
gets a row: status, code, tests, note. IDs without an evidence entry are
listed as 'not started' so nothing is silently skipped.

Run: python3 tools/reqindex/traceability.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "docs" / "traceability.md"

COVERED_LAYERS = {"1", "All"}


def main() -> None:
    reqs = json.loads((HERE / "requirements.json").read_text(encoding="utf-8"))
    trace = json.loads((HERE / "trace-layer1.json").read_text(encoding="utf-8"))
    patterns = {k[:-1]: v for k, v in trace.items() if k.endswith("*")}

    # Layer assignments come from build_index.py; reuse its rules.
    import importlib.util

    spec = importlib.util.spec_from_file_location("build_index", HERE / "build_index.py")
    bi = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    assert spec and spec.loader
    spec.loader.exec_module(bi)  # type: ignore[union-attr]

    rows = []
    for e in reqs:
        layer, _ = bi.layer_for(e["key"])
        if layer not in COVERED_LAYERS:
            continue
        entry = trace.get(e["key"])
        if entry is None:
            for prefix, v in patterns.items():
                if e["key"].startswith(prefix):
                    entry = v
                    break
        status, code, tests, note = entry if entry else ("not started", "", "", "")
        rows.append((e["key"], layer, status, code, tests, note, e["text"]))

    counts = Counter(r[2] for r in rows)
    out = [
        "# Traceability",
        "",
        "Generated by `tools/reqindex/traceability.py` from `tools/reqindex/trace-layer1.json`. "
        "Covers layer 1 and the cross-cutting requirements; later layers extend the evidence file. "
        "**Status**: `pass` = code and test evidence; `partial` = implemented with a stated gap; "
        "`deferred` = belongs to a later layer or an open decision; `designed` = cannot be proven on Docker Desktop (compliance or cloud).",
        "",
        "| Status | IDs |",
        "| --- | ---: |",
    ]
    for k in ("pass", "partial", "deferred", "designed", "not started"):
        if counts.get(k):
            out.append(f"| {k} | {counts[k]} |")
    out += ["", "| ID | Layer | Status | Code | Tests | Note |", "| --- | --- | --- | --- | --- | --- |"]
    for key, layer, status, code, tests, note, _ in rows:
        cell = lambda s: s.replace("|", "/")  # noqa: E731
        out.append(f"| {key} | {layer} | {status} | {cell(code)} | {cell(tests)} | {cell(note)} |")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} rows {dict(counts)}")


if __name__ == "__main__":
    main()
