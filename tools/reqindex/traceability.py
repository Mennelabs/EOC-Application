#!/usr/bin/env python3
"""Build docs/traceability.md from requirements.json and trace-layer<N>.json.

Every ID in build layers covered so far (layers 1 to 7 and the cross-cutting
set) gets a row: status, code, tests, note; a later layer's file overrides an
earlier entry for the same ID. IDs without an evidence entry are listed as
'not started' so nothing is silently skipped; an ID with an entry is listed
whatever its layer, so partial early deliveries stay visible.

Run: python3 tools/reqindex/traceability.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "docs" / "traceability.md"

COVERED_LAYERS = {"1", "2", "3", "4", "5", "6", "7", "All"}
TRACE_FILES = (
    "trace-layer1.json",
    "trace-layer2.json",
    "trace-layer3.json",
    "trace-layer4.json",
    "trace-layer5.json",
    "trace-layer6.json",
    "trace-partners.json",
    "trace-layer7.json",
)


def main() -> None:
    reqs = json.loads((HERE / "requirements.json").read_text(encoding="utf-8"))
    trace: dict = {}
    for name in TRACE_FILES:
        trace.update(json.loads((HERE / name).read_text(encoding="utf-8")))
    patterns = {k[:-1]: v for k, v in trace.items() if k.endswith("*")}

    # Layer assignments come from build_index.py; reuse its rules.
    import importlib.util

    spec = importlib.util.spec_from_file_location("build_index", HERE / "build_index.py")
    bi = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    assert spec and spec.loader
    spec.loader.exec_module(bi)  # type: ignore[union-attr]

    rows = []
    for e in reqs:
        layer, _ = bi.layer_for(e["key"])
        entry = trace.get(e["key"])
        if layer not in COVERED_LAYERS and entry is None:
            continue
        if entry is None:
            for prefix, v in patterns.items():
                if e["key"].startswith(prefix):
                    entry = v
                    break
        status, code, tests, note = entry if entry else ("not started", "", "", "")
        rows.append((e["key"], layer, status, code, tests, note, e["text"]))

    counts = Counter(r[2] for r in rows)
    out = [
        "# Traceability",
        "",
        "Generated by `tools/reqindex/traceability.py` from `tools/reqindex/trace-layer1.json`, `trace-layer2.json`, `trace-layer3.json`, `trace-layer4.json`, `trace-layer5.json`, `trace-layer6.json`, `trace-partners.json` (partner work before layer 7) and `trace-layer7.json`. "
        "Covers layers 1 to 7 and the cross-cutting requirements; later layers add an evidence file each. "
        "**Status**: `pass` = code and test evidence; `partial` = implemented with a stated gap; "
        "`deferred` = belongs to a later layer or an open decision; `designed` = cannot be proven on Docker Desktop (compliance or cloud); "
        "`not started` = no code or test evidence yet.",
        "",
        "| Status | IDs |",
        "| --- | ---: |",
    ]
    for k in ("pass", "partial", "deferred", "designed", "not started"):
        if counts.get(k):
            out.append(f"| {k} | {counts[k]} |")
    out += ["", "| ID | Layer | Status | Code | Tests | Note |", "| --- | --- | --- | --- | --- | --- |"]
    for key, layer, status, code, tests, note, _ in rows:
        cell = lambda s: s.replace("|", "/")  # noqa: E731
        out.append(f"| {key} | {layer} | {status} | {cell(code)} | {cell(tests)} | {cell(note)} |")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} rows {dict(counts)}")


if __name__ == "__main__":
    main()
